#!/bin/sh
# Write the winget manifests for one release.
#
#   make-manifests.sh <version> <sha256-of-windows-zip> <output-dir>
#
# winget manifests name one version, one URL and one hash, so they cannot be
# committed once and forgotten: the release workflow calls this after the
# archives are built, and the output is attached to the release. Submitting
# them to microsoft/winget-pkgs is a separate, reviewed step — the manifest is
# the input to it.
set -eu

version=${1:?usage: make-manifests.sh <version> <sha256> <output-dir>}
sha256=${2:?usage: make-manifests.sh <version> <sha256> <output-dir>}
out=${3:?usage: make-manifests.sh <version> <sha256> <output-dir>}

identifier=fuunshi.Netgap
archive="netgap-gui-$version-windows-x86_64.zip"
url="https://github.com/fuunshi/netgap/releases/download/v$version/$archive"

dir="$out/manifests/f/fuunshi/Netgap/$version"
mkdir -p "$dir"

cat >"$dir/$identifier.yaml" <<EOF
# Generated by packaging/winget/make-manifests.sh for the v$version release.
PackageIdentifier: $identifier
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
EOF

cat >"$dir/$identifier.locale.en-US.yaml" <<EOF
# Generated by packaging/winget/make-manifests.sh for the v$version release.
PackageIdentifier: $identifier
PackageVersion: $version
PackageLocale: en-US
Publisher: fuunshi
PublisherUrl: https://github.com/fuunshi
PackageName: Netgap
PackageUrl: https://github.com/fuunshi/netgap
License: MIT OR Apache-2.0
LicenseUrl: https://github.com/fuunshi/netgap/blob/main/LICENSE-MIT
Copyright: Copyright (c) Pranil Shrestha
ShortDescription: LAN security scanner with a window application.
Description: Finds the devices on the local network, what they expose and what that means. The window application shows a dashboard, a scan screen, a searchable device list and the scan history.
Tags:
  - network
  - security
  - scanner
  - lan
  - ports
  - security-tools
ManifestType: defaultLocale
ManifestVersion: 1.6.0
EOF

cat >"$dir/$identifier.installer.yaml" <<EOF
# Generated by packaging/winget/make-manifests.sh for the v$version release.
PackageIdentifier: $identifier
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
Installers:
  - Architecture: x64
    InstallerUrl: $url
    InstallerSha256: $sha256
    NestedInstallerFiles:
      - RelativeFilePath: netgap-gui.exe
        PortableCommandAlias: netgap-gui
ManifestType: installer
ManifestVersion: 1.6.0
EOF

echo "wrote $dir"
