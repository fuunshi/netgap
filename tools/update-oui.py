#!/usr/bin/env python3
"""Regenerate netgap-fingerprint/data/oui.csv from the IEEE registry.

Vendor lookup uses the public IEEE OUI assignments:

  * MA-L  (24-bit, 6 hex digits) — the bulk of real devices
  * MA-M  (28-bit, 7 hex digits)
  * MA-S  (36-bit, 9 hex digits)

Usage:
    python3 tools/update-oui.py

The output is committed so that builds are offline and reproducible; re-run
this only to refresh the data. Organization names are published by the IEEE
with legal suffixes ("Cisco Systems, Inc"), which are trimmed here because the
name is shown in a terminal table. Nothing else is altered.
"""

from __future__ import annotations

import csv
import io
import pathlib
import re
import sys
import urllib.request

SOURCES = [
    ("MA-L", "https://standards-oui.ieee.org/oui/oui.csv"),
    ("MA-M", "https://standards-oui.ieee.org/oui28/mam.csv"),
    ("MA-S", "https://standards-oui.ieee.org/oui36/oui36.csv"),
]

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "netgap-fingerprint" / "data" / "oui.csv"

# Trimmed only when they trail the name, so "AB" inside a word is untouched.
LEGAL_SUFFIXES = [
    "co., ltd.", "co.,ltd.", "co.,ltd", "co. ltd.", "co., ltd", "co. ltd",
    "corporation", "corp.", "corp", "company",
    "incorporated", "inc.", "inc", "llc", "l.l.c.", "ltd.", "ltd", "limited",
    "gmbh", "ag", "s.a.", "s.a", "sas", "s.p.a.", "b.v.", "bv", "a/s", "ab",
    "oy", "oyj", "k.k.", "pty ltd", "pty. ltd.", "s.r.o.", "d.o.o.", "co.",
]


def clean_name(raw: str) -> str:
    """Collapse whitespace and drop trailing legal suffixes."""
    name = " ".join(raw.split()).strip().strip(",").strip()

    changed = True
    while changed:
        changed = False
        lowered = name.lower()
        for suffix in LEGAL_SUFFIXES:
            # Require a word boundary so "Co." is only stripped as its own word.
            if lowered.endswith(suffix) and len(name) > len(suffix):
                trimmed = name[: -len(suffix)].rstrip(" ,.")
                if trimmed:
                    name, changed = trimmed, True
                break

    return name or raw.strip()


def fetch(url: str) -> str:
    # The IEEE endpoint answers 418 to the default urllib agent.
    request = urllib.request.Request(
        url, headers={"User-Agent": "netgap-oui-updater/1.0 (+https://github.com/fuunshi/netgap)"}
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read().decode("utf-8", errors="replace")


def main() -> int:
    entries: dict[str, str] = {}

    for registry, url in SOURCES:
        try:
            text = fetch(url)
        except Exception as error:  # noqa: BLE001 - reported to the user
            print(f"warning: could not fetch {registry} from {url}: {error}", file=sys.stderr)
            continue

        rows = 0
        for row in csv.DictReader(io.StringIO(text)):
            assignment = (row.get("Assignment") or "").strip().upper()
            organization = (row.get("Organization Name") or "").strip()

            if not assignment or not organization:
                continue
            if not re.fullmatch(r"[0-9A-F]{6,9}", assignment):
                continue

            entries[assignment] = clean_name(organization)
            rows += 1

        print(f"{registry}: {rows} assignment(s) from {url}")

    if not entries:
        print("error: no OUI data fetched; leaving the existing file untouched", file=sys.stderr)
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8") as handle:
        handle.write("# IEEE OUI assignments, generated by tools/update-oui.py — do not edit.\n")
        handle.write("# Format: <assignment in hex>,<organization>\n")
        for assignment in sorted(entries):
            handle.write(f"{assignment},{entries[assignment]}\n")

    size_kb = OUTPUT.stat().st_size / 1024
    print(f"wrote {len(entries)} entries to {OUTPUT} ({size_kb:.0f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
